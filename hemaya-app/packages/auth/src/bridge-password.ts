/* ============================================================
   كلمة سرّ جسر نفاذ التجريبيّ — مصدرٌ واحدٌ لها، وحارسٌ يمنع تسرّبها للإنتاج.

   الجسر آليةُ عرضٍ مؤقّتة: يوثّق الهوية بنفاذٍ محاكى ثم يفتح جلسة Supabase
   بكلمةٍ موحّدة. وقيمتها الافتراضية مكتوبةٌ في الشيفرة، والشيفرة مفتوحة —
   ومعها في الملف نفسه صيغةُ البريد (‏{الهوية}@nafath.local) وخريطةُ
   الهوية→الدور. فمن بلغ Supabase وهي على الافتراضيّ دخل بأيّ دور
   (رئيس المركز، النائب العام، أيّ مستفيد) عبر signInWithPassword مباشرةً،
   دون المرور بالجسر أصلاً.

   لذلك: الافتراضيّ مقبولٌ في التطوير وحده. وفي الإنتاج تُضبط
   NAFATH_BRIDGE_PASSWORD أو يُرفَض الإقلاع — لا فشلٌ صامتٌ إلى الافتراضيّ.
   والغاية النهائية إزالة الجسر كلّه عند وصل نفاذ الحقيقيّ (OIDC، بلا كلمة سرّ).
   ============================================================ */

const DEV_FALLBACK = "nafath-staff-2026";

/** بيئةُ إنتاجٍ فعليّة (لا تطوير ولا اختبار). */
function isProduction(): boolean {
  const env = process.env.APP_ENV ?? process.env.NODE_ENV ?? "development";
  return env === "production";
}

/**
 * كلمة سرّ الجسر.
 * @throws في الإنتاج إن لم تُضبط NAFATH_BRIDGE_PASSWORD — كي لا يعمل
 *         نظامٌ حيٌّ بكلمةٍ منشورةٍ في مستودعٍ عام.
 */
export function bridgePassword(): string {
  const fromEnv = process.env.NAFATH_BRIDGE_PASSWORD;
  if (fromEnv && fromEnv.trim()) return fromEnv;

  if (isProduction()) {
    throw new Error(
      "NAFATH_BRIDGE_PASSWORD غير مضبوطة في بيئة إنتاج — " +
      "الكلمة الافتراضية منشورةٌ في الشيفرة ولا يجوز الاعتماد عليها. " +
      "اضبط المتغيّر، أو أزِل جسر نفاذ التجريبيّ ووصّل نفاذ الحقيقيّ."
    );
  }
  return DEV_FALLBACK;
}
