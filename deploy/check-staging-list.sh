#!/usr/bin/env bash
# ============================================================
#  حارس قائمة النشر — يمنع تكرار فجوةٍ وقعت مرّتين
#
#  قائمة MIGRATIONS في oneshot صريحةٌ لا glob (وهذا مقصود: الترتيب
#  يهمّ، وبعض المهاجرات لا تصحّ إعادةُ تطبيقها). لكنّ ثمنه أنّ كل
#  مهاجرةٍ تُدمج في main يجب أن تُضاف يدويّاً — ومَن ينسى لا يكتشف
#  الأمر إلا حين تنهار التجريبية بعد النشر:
#    · 2026-08-11: أربع مهاجرات (#99 · #100 · #102 · #103) بقيت خارجها.
#    · 2026-08-16: تسع مهاجرات — منها المرفقات والعطل والواردة الحيّة.
#
#  الشيفرة تبلغ التجريبية بـredeploy والمهاجرات لا؛ فالنتيجة واجهةٌ
#  تنادي دوالَّ غير موجودة. هذا الحارس يجعل النسيان خطأً مرئيّاً.
#
#  الاستعمال:  ./deploy/check-staging-list.sh        (يفشل عند النقص)
#  وفي خطّاف pre-push يُستدعى تلقائياً.
# ============================================================
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
LIST="$ROOT/deploy/staging/oneshot-2026-08-10.sh"
MIG="$ROOT/supabase/migrations"

[ -f "$LIST" ] || { echo "✗ قائمة النشر غير موجودة: $LIST" >&2; exit 1; }

# حدّ البدء من السكربت نفسه — ما قبله مطبَّقٌ على التجريبية ولا يُدرج.
FROM=$(grep -oE 'FROM_VERSION="\$\{FROM_VERSION:-[0-9]+\}"' "$LIST" | grep -oE '[0-9]{14}' | head -1)
[ -n "$FROM" ] || { echo "✗ تعذّر استخراج FROM_VERSION من القائمة." >&2; exit 1; }

# المقارنة على رقم النسخة لا على اسم الملف: الاسم الكامل أطولُ من الرقم
# فيبدو دائماً «أكبر» منه، فتُحسب مهاجرةُ الحدّ نفسها ناقصةً.
on_disk=$(ls "$MIG" | grep -E '^[0-9]{14}_.*\.sql$' \
          | awk -v f="$FROM" '{ v = substr($0, 1, 14); if (v > f) print }' | sort)
in_list=$(grep -oE '2026[0-9]{10}_[^"]+\.sql' "$LIST" | sort -u)

missing=$(comm -23 <(echo "$on_disk") <(echo "$in_list"))
ghost=$(comm -13 <(echo "$on_disk") <(echo "$in_list") \
        | while read -r m; do [ -n "$m" ] && [ ! -f "$MIG/$m" ] && echo "$m"; done)

fail=0
if [ -n "$missing" ]; then
  fail=1
  echo "✗ مهاجرات في المستودع وليست في قائمة نشر التجريبية (لن تصلها أبداً):" >&2
  echo "$missing" | sed 's/^/    /' >&2
fi
if [ -n "$ghost" ]; then
  fail=1
  echo "✗ مهاجرات مُدرَجة في القائمة ولا وجود لملفّها (سيتوقّف السكربت عندها):" >&2
  echo "$ghost" | sed 's/^/    /' >&2
fi

if [ $fail -eq 1 ]; then
  echo >&2
  echo "  أضِفها إلى MIGRATIONS في deploy/staging/oneshot-2026-08-10.sh بترتيبها،" >&2
  echo "  فالقائمة صريحةٌ لا glob والترتيب مقصود." >&2
  exit 1
fi

echo "✓ قائمة النشر مكتملة — $(echo "$on_disk" | grep -c . ) مهاجرة بعد $FROM، كلّها مُدرَجة."
