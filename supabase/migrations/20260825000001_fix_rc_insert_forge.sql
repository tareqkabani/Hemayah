--  الحال قبل اليوم: سياسةُ الإدخال على risk_classifications بلا شرطٍ
--  إطلاقاً، والمِنَحُ الشاملةُ تعطي insert لكلّ authenticated. فأيُّ حاملِ
--  جلسة — حتى طالبُ حمايةٍ عاديّ — يُدخل صفّاً بأيّ case_id وأيّ level
--  وأيّ assessor_id. وخاصيّةُ «الإلحاق فقط» (سحبُ update/delete) تجعل
--  الصفَّ المزوَّر غيرَ قابلٍ للتصحيح — فالحمايةُ المقصودةُ تخدم المزوِّر.
--
--  أُثبت حيّاً: طالبُ حمايةٍ (أدنى امتياز) أدخل تصنيفاً على قضيّةٍ لا
--  يملكها → نجح (INSERT 0 1)؛ وعبر PostgREST بتوكن حسابٍ من التسجيل
--  الذاتيّ → HTTP 201 والصفُّ ثبت.
--
--  لماذا سحبُ الإدخال كليّاً لا تضييقُ الشرط: الجدولُ خامدٌ تماماً —
--  صفرُ صفوفٍ حيّة، ولا كاتبَ له في أيّ مهاجرةٍ أو شيفرةِ تطبيق (منطقُ
--  الخطورة الحيّ يعيش في recommendations.factors9). فلا ميزةَ تنكسر،
--  والنمطُ المعياريّ في المنصّة لجدولٍ كهذا: RLS بلا سياسةِ كتابةٍ =
--  رفضٌ كامل، والكتابةُ — إن أُحيي التقييمُ — عبر دالّة SECURITY DEFINER
--  تفرض الدور وتُثبّت assessor_id := auth.uid() (كنمط الأحد عشر جدولاً
--  المحكومةِ بالدوالّ: api_keys · board_decisions · measures …).
--
--  idempotent · بلا أثرٍ على البيانات (الجدول فارغ).
-- ============================================================

-- 1) أسقِط السياسةَ المفتوحة.
drop policy if exists rc_insert on risk_classifications;

-- 2) اسحب صلاحيةَ الإدخال عن authenticated — لا كاتبَ مباشراً يحتاجها.
--    (القراءةُ تبقى بـ rc_select: case_officer/board_member.)
revoke insert on risk_classifications from authenticated;

-- 3) وثّق النيّةَ للمستقبل: أيُّ إحياءٍ للتقييم يمرّ بدالّةٍ محكومة، لا
--    بمنحٍ مباشر. (لا فعلَ هنا — تعليقٌ موجِّهٌ على الجدول.)
comment on table risk_classifications is
  'خامدٌ حالياً — إن أُحيي: تُكتب عبر دالّة SECURITY DEFINER تفرض الدور وassessor_id=auth.uid(). لا منحَ insert مباشراً (HMY-09).';
