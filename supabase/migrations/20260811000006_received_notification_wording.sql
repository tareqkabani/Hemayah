-- ============================================================
--  صياغة إشعار استلام الطلب (n_received)
--
--  النصّ كان يَعِد بمهلة الفرز ويحيل إلى صفحة «طلباتي»:
--    «… الطلب قيد الفرز المبدئي، وستصلكم نتيجته خلال {مهلة_الفرز}.
--      يمكنكم متابعة الطلب من صفحة «طلباتي».»
--  والصياغة المعتمدة تقف عند حالة الطلب:
--    «… الطلب قيد الفرز المبدئي،»
--
--  المتغيّر {مهلة_الفرز} يسقط من النصّ تبعاً لذلك، ويُعاد احتساب عمود
--  variables من النصّ نفسه (المحرّك يكتشف المتغيّرات وقت الإرسال لا من
--  هذا العمود — فبقاء 'مهلة_الفرز' في حمولة notify_from_template غير ضارّ).
--
--  الإشعارات المُرسَلة سلفاً لا تُمسّ — نصّها محفوظٌ في صفّها وقت إنشائه.
-- ============================================================

update notification_templates set
  body = 'وصلنا طلبكم برقم {رقم_الطلب} بتاريخ {تاريخ_التقديم}، ورمزكم السري ({الرمز_السري}) فاحتفظوا به. الطلب قيد الفرز المبدئي،'
where template_key = 'n_received';

update notification_templates set variables = (
  select coalesce(array_agg(distinct m[1]), '{}')
  from regexp_matches(subject || ' ' || body, '\{([^}]+)\}', 'g') as m)
where template_key = 'n_received';
